// String 返回三字母币种代码；无效币种返回空字符串。
func (c Currency) String() (code string) {
	if offset := (int(c) - 1) * 3; offset >= 0 && offset < len(currencyCodes) {
		code = currencyCodes[offset : offset+3]
	}
	return
}
